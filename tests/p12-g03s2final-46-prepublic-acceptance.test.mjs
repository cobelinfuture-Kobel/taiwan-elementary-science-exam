import test from "node:test";
import assert from "node:assert/strict";
import {readFileSync} from "node:fs";
const read=p=>JSON.parse(readFileSync(p,"utf8"));
test("historical PrePublic acceptance and fishbowl adjudication remain immutable after separate public authorization",()=>{
 const science=read("data/review/p12-g03s2final-fishbowl-operator-science-adjudication-v1.json");
 const correction=read("data/review/p12-g03s2final-composite-p03-q03-science-correction-v1.json");
 const source=read("data/review/p12-g03s2final-46-final-source-acceptance-v1.json");
 const stage=read("data/staging/p12-g03s2final-46-learner-blocks-v1.json");
 const report=read("data/review/p12-g03s2final-46-prepublic-acceptance-v1.json");
 const operator=read("site/data/governance/p12-g03s2final-46-operator-public-approval-v1.json");
 const id=science.approved_source_slot_id;
 assert.equal(source.items.find(x=>x.source_slot_id===id)?.independent_science_answer,"O");
 assert.equal(science.approved_learner_answer,"X");
 assert.equal(correction.new_approved_learner_answer,"X");
 assert.equal(correction.original_science_review_preserved,true);
 assert.equal(science.teacher_answer_key_authenticated,false);
 assert.equal(stage.public_site_integrated,false,"historical staging is not retroactively rewritten");
 assert.equal(stage.operator_public_release_approved,false);
 assert.equal(report.decision,"PREPUBLIC_ACCEPTANCE_PASS__BULK_PUBLIC_RELEASE_NOT_AUTHORIZED");
 assert.equal(report.public_boundary.public_answer_slots_before_and_after,205);
 assert.equal(report.prepublic_candidate_blocks,28);
 assert.equal(report.prepublic_candidate_source_slots,46);
 assert.equal(operator.approved_slot_count,46);
 assert.equal(operator.expected_total_public_answer_slots,251);
 assert.equal(operator.fishbowl_science_adjudication_ref,"data/review/p12-g03s2final-fishbowl-operator-science-adjudication-v1.json");
 assert.equal(operator.approved_items.find(x=>x.source_slot_id===id)?.answer,"X");
});
