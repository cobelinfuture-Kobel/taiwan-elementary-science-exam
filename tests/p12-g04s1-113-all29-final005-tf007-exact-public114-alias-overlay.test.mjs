const publicBank=read('site/data/question-bank/p12-b04-b04-47-public-v1.json');
test('FINAL005 TF007 exact original 113 alias of 114 already-published bank, preserve student record and KP',()=>{
 const item=publicBank.blocks.filter(x=>x.id===exact.existing_student_item_id);
 assert.equal(item.length,1);
 assert.equal(item[0].source_slot_id,exact.existing_student_item_source_slot_id);
 assert.equal(item[0].stem,exact.original_exam_stem);
 assert.equal(item[0].answer,exact.existing_student_answer);
 assert.equal(item[0].canonical_kp_id,exact.existing_student_original_canonical_kp_unchanged);
 assert.equal(item[0].operator_publication_approval,true);
 assert.equal(exact.duplicate_gate,'FULL_VERBATIM_EXACT_STEM_ALIAS_TO_ALREADY_PUBLISHED_STUDENT_ITEM');
 assert.equal(exact.source_slot_id,'SCI_G04_S1_113_FINAL_005|S01|TF|007');
 assert.equal(exact.original_pdf_sha256,'94108a241a9833fda111ba7648ea4e1c424e5a64d84a090c42e4c9777c5218ec');
 assert.deepEqual(exact.original_native_answer_bbox_pdf_points_top_left,[42.12,344.2,90.12,356.2]);
 assert.equal(exact.new_student_item_allowed,false);
 assert.equal(exact.student_site_publication_new,0);
});
test('one original unreviewed work slot changed to alias without changing 333 published or earlier hold overlays',()=>{
 assert.equal(ledger.known_atomic_source_dispositions.length,1762);
 assert.deepEqual(prior.after_effective_disjoint,exact.previous_source_work_disjoint);
 const row=ledger.known_atomic_source_dispositions.find(x=>x.source_slot_id===exact.source_slot_id);
 assert.equal(row.disposition,'UNREVIEWED');
 const map=new Map(ledger.known_atomic_source_dispositions.map(r=>[r.source_slot_id,r.disposition]));
 map.set('SCI_G04_S1_113_FINAL_001|S02|MC|008','HOLD');
 for(const x of prior.exact_seven_original_source_slots)map.set(x.source_slot_id,'HOLD');
 map.set(exact.source_slot_id,'ALIAS');
 assert.equal(map.size,1762);
 const counts={PUBLISHED:0,HOLD:0,ALIAS:0,UNREVIEWED:0};
 for(const status of map.values())counts[status]++;
 assert.deepEqual(counts,exact.effective_source_work_disjoint);
 assert.deepEqual(counts,{PUBLISHED:333,HOLD:291,ALIAS:16,UNREVIEWED:1122});
 assert.equal(exact.main_student_published_113_source_positions_remain,333);
 assert.equal(exact.formal_new_science_kp_approved,0);
 assert.equal(exact.admission_ready_new,0);
});
