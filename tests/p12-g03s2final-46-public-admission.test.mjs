import test from "node:test";
import assert from "node:assert/strict";
import {readFileSync} from "node:fs";
import {validateAndConvertP12G03Final46} from "../site/assets/js/p12-g03s2final-46-release.mjs";
import {buildMaster} from "../tools/p12-master-progress.mjs";
const read=x=>JSON.parse(readFileSync(x,"utf8"));
const bank=read("site/data/question-bank/p12-g03s2final-46-public-v1.json");
const approval=read("site/data/governance/p12-g03s2final-46-operator-public-approval-v1.json");
const source=read("data/review/p12-g03s2final-46-final-source-acceptance-v1.json");
const originalBank=read("site/data/question-bank/approved-historical-ox-v4.json");
const authority=read("site/data/authority/science-g03-g04-selector-v2.json");
const fish="G03-S2-FINAL|COMPOSITE|P03|003";
test("public admission validates all 28 blocks and 46 source slots against operator approval",()=>{
 const result=validateAndConvertP12G03Final46(bank,approval,authority);
 assert.equal(result.answerSlots,46);
 assert.equal(result.standaloneTf,6);
 assert.equal(result.standaloneChoice,14);
 assert.equal(result.contextGroups,8);
 assert.equal(result.figureGroups,6);
 assert.equal(result.readingGroups,2);
 assert.equal(result.blocks.length,28);
 assert.equal(new Set(result.blocks.map(x=>x.id)).size,28);
 assert.equal(approval.approved_slot_count,46);
 assert.equal(approval.preexisting_public_answer_slots,205);
 assert.equal(approval.expected_total_public_answer_slots,251);
 assert.equal(bank.expected_deployed_bank_answer_slots,251);
});
test("fishbowl original teacher O retained and approved X released exactly once",()=>{
 const historic=source.items.find(x=>x.source_slot_id===fish);
 const released=bank.blocks.find(x=>x.id==="P12_G03S2FINAL_COMPOSITE_P03");
 const current=released.items.find(x=>x.source_slot_id===fish);
 const a=approval.approved_items.find(x=>x.source_slot_id===fish);
 assert.equal(historic.independent_science_answer,"O");
 assert.equal(historic.original_teacher_key_authenticated,false);
 assert.equal(current.answer,"X");
 assert.equal(a.answer,"X");
 assert.equal(a.science_exception_ref,"data/review/p12-g03s2final-composite-p03-q03-science-correction-v1.json");
 assert.equal(released.figure_spec.labels[2],"曲面小魚缸");
 assert.deepEqual(released.items.map(x=>x.answer),["O","X","X","O"]);
});
test("public source IDs are disjoint from eight already published G03 final TF positions",()=>{
 const ids=new Set(bank.blocks.flatMap(b=>(b.type==="group"?b.items:[b]).map(x=>x.source_slot_id)));
 assert.equal(ids.size,46);
 for(let i=2;i<=9;i++)assert.ok(!ids.has("G03-S2-FINAL|TF|P01|"+String(i).padStart(3,"0")));
 assert.equal(originalBank.blocks.filter(x=>x.source_id==="G03-S2-FINAL").length,8);
});
test("final release fails closed for unsupported answer, KP, figure mismatch, omitted or duplicated source slot",()=>{
 const clone=x=>structuredClone(x);
 let x=clone(bank);
 x.blocks.find(b=>b.id==="P12_G03S2FINAL_COMPOSITE_P03").items[2].answer="O";
 assert.throws(()=>validateAndConvertP12G03Final46(x,approval,authority),/魚缸|來源位置/);
 x=clone(bank);
 x.blocks[0].canonical_kp_id="NONEXISTENT";
 assert.throws(()=>validateAndConvertP12G03Final46(x,approval,authority),/KP/);
 x=clone(bank);
 x.blocks.find(b=>b.id==="P12_G03S2FINAL_COMPOSITE_P03").figure_spec.labels[2]="直壁小魚缸";
 assert.throws(()=>validateAndConvertP12G03Final46(x,approval,authority),/魚缸/);
 x=clone(bank);x.blocks.pop();
 assert.throws(()=>validateAndConvertP12G03Final46(x,approval,authority),/來源數量/);
 x=clone(bank);x.blocks[0].source_slot_id=x.blocks[1].source_slot_id;
 assert.throws(()=>validateAndConvertP12G03Final46(x,approval,authority),/位置|slot 順序/);
 x=clone(bank);x.blocks[0].original_teacher_answer_key_authenticated=true;
 assert.throws(()=>validateAndConvertP12G03Final46(x,approval,authority),/來源/);
 x=clone(bank);x.blocks.find(b=>b.figure_spec).figure_spec.preserveAspectRatio="none";
 assert.throws(()=>validateAndConvertP12G03Final46(x,approval,authority),/SVG/);
});
test("append-only public ledger exactly releases G03 final 46 while preserving 205 source baseline",()=>{
 const e=read("site/data/governance/p12-review-events.json").events;
 assert.equal(e.length,320);
 const newly=e.slice(274);
 assert.equal(newly.length,46);
 assert.ok(newly.every(x=>x.action==="PUBLIC_ADMIT"&&x.publication_approved===true));
 assert.equal(new Set(newly.map(x=>x.source_slot_id)).size,46);
 assert.equal(newly.find(x=>x.source_slot_id===fish).public_source_slot_answer,"X");
 const master=buildMaster();
 assert.equal(master.public_question_bank_answer_slots_current,251);
 assert.equal(master.p12_operator_published_slots,103);
 assert.equal(master.position_status_counts.certified_staged,0);
 assert.equal(master.position_status_counts.published,103);
 assert.equal(master.position_status_counts.not_started,223);
 assert.equal(master.review_events_count,320);
 assert.equal(master.paper_rows.find(p=>p.source_id==="G03-S2-FINAL").published,46);
});
