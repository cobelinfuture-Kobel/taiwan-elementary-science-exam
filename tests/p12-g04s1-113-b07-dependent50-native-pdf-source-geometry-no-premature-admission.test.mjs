import test from 'node:test';
import assert from 'node:assert/strict';
import {readFileSync} from 'node:fs';
const read=(p)=>JSON.parse(readFileSync(new URL('../data/review/'+p,import.meta.url),'utf8'));
const ledger=read('p12-g04s1-113-b07-dependent50-originalpdf-ninepages-nativebbox-science-kp-hold-v1.json');
const old=read('p12-g04s1-113-other-dependent-b07-source-parent-preflight-v1.json');
const shihu=read('p12-g04s1-113-p04b-shihu-mid50-native-original-source-bbox-v1.json');
const lushang=read('p12-g04s1-113-p04b-lushang-mid50-native-answer-and-matching-bbox-v1.json');
const guangxing=read('p12-g04s1-113-p04b-guangxing-mid54-original-native-plus-vector-answer-frames-v1.json');
const published=read('p12-g04s1-113-main-published309-source-suppression-readback-v18.json');
const sources=[...shihu.records,...lushang.records,...guangxing.records];
const norm=(s)=>s.split('|').map((s,i)=>i===1&&/^S0+\d+$/.test(s)?'S'+Number(s.slice(1)):i>1&&/^G0+\d+$/.test(s)?'G'+Number(s.slice(1)):i>1&&/^0+\d+$/.test(s)?String(Number(s)):s).join('|');
test('B07 50 original PDF physical markers reconcile without modifying the frozen preflight',()=>{
 assert.equal(ledger.counts.source_positions,50);
 assert.equal(old.records.length,50);
 assert.equal(ledger.records.length,50);
 assert.equal(ledger.counts.matching_actual_pdf_answer_geometry,50);
 assert.equal(ledger.counts.independent_printed_answer_or_vector_frame_regions,47);
 assert.equal(ledger.counts.matching_anchor_only,3);
 assert.equal(ledger.counts.original_legacy_section_mismatch,3);
 const registered=new Set(published.all_unique_published_source_slot_ids.map(norm));
 const ids=new Set();
 for(let i=0;i<50;i++){
  const x=ledger.records[i],oldRow=old.records[i],src=sources.find(s=>s.source_slot_id===x.original_native_source_slot_id);
  assert.equal(x.worklist_ordinal,i+301);
  assert.equal(oldRow.other_lane_ordinal,i+301);
  assert.equal(x.legacy_source_slot_id,oldRow.source_slot_id);
  assert.equal(x.paper_id,oldRow.paper_id);
  assert.equal(x.original_pdf_sha256,oldRow.original_pdf_sha256);
  assert.ok(src,'Missing original native marker '+x.worklist_ordinal);
  assert.deepEqual(x.original_physical_bbox_pdf_pts_top_left,src.original_source_marker_bbox_pt??src.original_answer_marker_or_frame_bbox_pt);
  assert.equal(x.source_page_1_based,src.original_pdf_page);
  assert.ok(x.source_page_1_based>=1&&x.source_page_1_based<=3);
  assert.ok(!ids.has(x.original_native_source_slot_id));ids.add(x.original_native_source_slot_id);
  assert.ok(!registered.has(norm(x.original_native_source_slot_id)));
  assert.equal(x.exact_original_source_text_and_all_options_admission_certified,false);
  assert.equal(x.science_KP_formal_approved,false);
  assert.equal(x.full_113_114_semantic_duplicate_proof_accepted,false);
  assert.equal(x.figure_or_parent_rights_accepted,false);
  assert.equal(x.operator_exact_cohort_approved,false);
  assert.equal(x.admission_ready,false);
  assert.equal(x.published_new,false);
 }
 assert.equal(ids.size,50);
 assert.deepEqual(ledger.records.slice(-3).map(x=>x.original_native_source_slot_id),[1,2,3].map(i=>'SCI_G04_S1_113_MID_015|S05|G01|SHORT|'+String(i).padStart(3,'0')));
 assert.ok(ledger.records.slice(-3).every(x=>x.legacy_section_id_mismatch===true && x.existing_gate_flags.includes('OPEN_ENDED_NO_UNIQUE_ANSWER')));
 assert.deepEqual(ledger.counts.formal_science_kp_approved_new,0);
 assert.deepEqual(ledger.counts.admission_ready_new,0);
 assert.deepEqual(ledger.counts.published_new,0);
 assert.equal(ledger.counts.live_public_answer_slots_unchanged,945);
});
