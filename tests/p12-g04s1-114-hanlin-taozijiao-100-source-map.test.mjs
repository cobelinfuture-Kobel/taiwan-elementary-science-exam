import test from "node:test";
import assert from "node:assert/strict";
import {readFileSync} from "node:fs";
import {classifyG04S1SourcePosition} from "../tools/p12-g04s1-kp-first.mjs";
import {buildMaster} from "../tools/p12-master-progress.mjs";
const read=p=>JSON.parse(readFileSync(p,"utf8"));
const source=read("data/review/p12-g04s1-114-hanlin-taozijiao-final-100-kp-first-text-map-v1.json");
const status=read("data/review/p12-g04s1-114-all25-kp-first-progress-v3.json");
const authority=read("site/data/authority/science-g03-g04-selector-v2.json");
test("114 Hanlin source has exactly 100 printed answer positions across 16 groups, no full image/answer acceptance claim",()=>{
 assert.equal(source.source_answer_positions_identified,100);
 assert.equal(source.source_section_counts.length,16);
 assert.equal(source.source_section_counts.reduce((a,b)=>a+b,0),100);
 assert.equal(source.items.length,100);
 assert.equal(new Set(source.items.map(x=>x.source_slot_id)).size,100);
 assert.equal(source.items.filter(x=>x.source_image_required).length,10);
 assert.deepEqual(source.first_pass_counts,{NONMATCH_G04S1_KP_ARCHIVE:42,KP_MATCH_CANDIDATE:34,KP_MATCH_SOURCE_EVIDENCE_HOLD:15,REVIEW_KP_UNCERTAIN:9});
 assert.equal(source.science_answer_verified_count,0);
 assert.equal(source.source_pdf_sha256,null);
 assert.equal(source.public_release_approved,false);
 assert.ok(source.items.every(x=>x.original_teacher_answer_key_authenticated===false&&!x.public_release_approved));
});
test("acidity-heavy paper still keeps sound/light source questions by G04S1 KP, including the moon light-source statement",()=>{
 const acid=source.items.filter(x=>x.original_section===1||x.original_section===2);
 assert.equal(acid.length,17);
 assert.ok(acid.every(x=>x.kp_first_decision==="NONMATCH_G04S1_KP_ARCHIVE"));
 const eligible=source.items.filter(x=>x.matched_canonical_kp_ids.length>0);
 assert.equal(eligible.length,49);
 const moon=source.items.find(x=>x.source_slot_id==="SCI_G04_S1_114_FINAL_012|Q03|007");
 assert.equal(moon.kp_first_decision,"KP_MATCH_CANDIDATE");
 assert.deepEqual(moon.matched_canonical_kp_ids,["sci_g04s1_03_05"]);
 const e=classifyG04S1SourcePosition({matched_canonical_kp_ids:moon.matched_canonical_kp_ids,original_paper_exam_type:"FINAL",original_publisher_label:"翰林",original_paper_scope_rating:"WRONG_SCOPE"},authority);
 assert.equal(e.decision,"KP_MATCH_CANDIDATE");
 assert.equal(e.retain_source,true);
 assert.deepEqual(e.new_curriculum_exam_routing,["CURRENT_FINAL"]);
});
test("image-dependent Q13/15 are retained, never published or science-answer certified",()=>{
 const selected=source.items.filter(x=>x.original_section===13||x.original_section===15);
 assert.equal(selected.length,10);
 assert.ok(selected.every(x=>x.kp_first_decision==="KP_MATCH_SOURCE_EVIDENCE_HOLD"));
 assert.ok(selected.every(x=>x.source_image_required===true&&x.source_image_verified===false&&x.science_answer_verified===false));
 assert.ok(selected.every(x=>x.matched_canonical_kp_ids.length===1));
});
