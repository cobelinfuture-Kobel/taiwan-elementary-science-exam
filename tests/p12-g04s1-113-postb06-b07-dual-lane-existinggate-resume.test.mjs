import test from 'node:test';
import assert from 'node:assert/strict';
import fs from 'node:fs';
const read = (p) => JSON.parse(fs.readFileSync(new URL('../'+p, import.meta.url),'utf8'));
test('B07 source-only 1 TFMC + 50 dependent are separate immutable lanes, never public', () => {
 const c=read('data/review/p12-g04s1-113-postb06-b07-dual-lane-1tfmc-50dependent-existinggate-resume-v1.json');
 const q=read('data/review/p12-g04s1-113-native-tfmc-b07-1-source-checkpoint-v1.json');
 const t=read('data/review/p12-g04s1-113-native-tfmc-b07-1-pdf-text-source-v1.json');
 const b=read('data/review/p12-g04s1-113-native-tfmc-b07-1-original-native-glyph-bbox-v1.json');
 const s=read('data/review/p12-g04s1-113-native-tfmc-b07-1-science-kp-context-routing-v1.json');
 const o=read('data/review/p12-g04s1-113-other-dependent-b07-source-parent-preflight-v1.json');
 assert.equal(c.status,'SOURCE_ONLY_B07_TRIAGE_NO_ADMISSION_NO_STUDENT_RELEASE');
 assert.equal(c.as_of_main_sha,'3e721d14713102e0f9e878889b9cbed99cdd7cb8');
 assert.equal(c.as_of_main_status.answer_slots,945);
 assert.equal(c.as_of_main_status.published_113_canonical_source_ids,309);
 assert.deepEqual(c.formal_delta_this_checkpoint,{FORMAL_SCIENCE_KP_APPROVED:0,ADMISSION_READY:0,PUBLISHED:0});
 assert.equal(c.source_lanes.length,2);
 const [tf,dependent]=c.source_lanes;
 assert.equal(tf.source_positions,1);
 assert.deepEqual(tf.original_ordinals,[301,301]);
 assert.equal(tf.record.source_slot_id,q.records[0].source_slot_id);
 assert.equal(tf.record.source_slot_id,t.source_records[0].source_slot_id);
 assert.equal(tf.record.source_slot_id,b.source_positions[0].source_slot_id);
 assert.equal(tf.record.source_slot_id,s.records[0].source_slot_id);
 assert.equal(tf.record.exact_original_question_text,t.source_records[0].original_pdf_text_layer_question);
 assert.deepEqual(tf.record.answer_bbox_pdf_pts_top_left,b.source_positions[0].original_answer_parenthesis_bbox_pts_top_left);
 assert.equal(tf.record.disposition,'HOLD_PARENT_READING_CONTEXT_EXISTING_GATE');
 assert.equal(tf.record.admission_ready,false);
 assert.equal(tf.record.published,false);
 assert.equal(dependent.source_positions,50);
 assert.deepEqual(dependent.original_ordinals,[301,350]);
 assert.equal(dependent.records.length,50);
 assert.equal(o.records.length,50);
 const ids=new Set();
 for(let i=0;i<50;i++){
  const a=dependent.records[i],original=o.records[i];
  assert.equal(a.source_slot_id,original.source_slot_id);
  assert.equal(a.other_lane_ordinal,original.other_lane_ordinal);
  assert.deepEqual(a.existing_missing_evidence_flags,original.potential_missing_gate_evidence);
  assert.equal(a.disposition,'HOLD_EXISTING_GATE_EVIDENCE_INCOMPLETE');
  assert.equal(a.formal_science_kp_approved,false);
  assert.equal(a.admission_ready,false);
  assert.equal(a.published,false);
  assert.ok(!ids.has(a.source_slot_id));
  ids.add(a.source_slot_id);
 }
 assert.ok(!ids.has(tf.record.source_slot_id),'TFMC B07 and dependent B07 must not share source identity');
 assert.equal(c.no_changes_to.includes('B01_B06_RELEASES'),true);
});
